public class Variables {
    public static void main(String[] args){
        int num = 10;
        System.out.println(num);
        
        //reutilziar la variable
        num += 30;
        System.out.println(num);
        
        //variable tipo string
        String texto = "hola mundo";
        System.out.println(texto);
        //reuizar la variables
        texto = "que onda";
        System.out.println(texto);
    }  
}